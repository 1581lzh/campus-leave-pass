package web

import "net/http"

// routes registers every page and action. All mutating actions are POST and
// pass through the CSRF middleware.
func (s *Server) routes(mux *http.ServeMux) {
	// Public.
	mux.HandleFunc("GET /{$}", s.home)
	mux.HandleFunc("GET /login", s.loginPage)
	mux.HandleFunc("POST /login", s.loginPost)
	mux.HandleFunc("GET /register", s.registerInfo)
	mux.HandleFunc("GET /staff/login", s.staffLoginPage)
	mux.HandleFunc("POST /staff/login", s.staffLoginPost)
	mux.HandleFunc("GET /staff/register", s.staffRegisterPage)
	mux.HandleFunc("POST /staff/register", s.staffRegisterPost)
	mux.HandleFunc("GET /admin/login", s.adminLoginPage)
	mux.HandleFunc("POST /admin/login", s.adminLoginPost)
	mux.HandleFunc("GET /forgot-password", s.forgotPage)
	mux.HandleFunc("POST /forgot-password", s.forgotPost)
	mux.HandleFunc("GET /admin/forgot-password", s.adminForgotPage)
	mux.HandleFunc("POST /admin/forgot-password", s.adminForgotPost)
	mux.HandleFunc("GET /reset-password", s.resetPage)
	mux.HandleFunc("POST /reset-password", s.resetPost)
	mux.HandleFunc("GET /recover", s.recoverPage)
	mux.HandleFunc("POST /recover", s.recoverPost)
	mux.HandleFunc("GET /recover/status", s.recoverStatus)
	mux.HandleFunc("POST /logout", s.logout)
	mux.HandleFunc("GET /p/{token}", s.gatePage)
	mux.HandleFunc("GET /a/{token}", s.proxyPage)
	mux.HandleFunc("POST /a/{token}", s.proxyPost)
	mux.HandleFunc("GET /healthz", s.healthz)

	// Student.
	mux.HandleFunc("GET /s", s.studentDashboard)
	mux.HandleFunc("GET /s/leave/new", s.studentLeaveNew)
	mux.HandleFunc("POST /s/leave/new", s.studentLeaveSubmit)
	mux.HandleFunc("GET /s/leaves", s.studentLeaves)
	mux.HandleFunc("GET /s/leaves/{id}", s.studentLeaveDetail)
	mux.HandleFunc("POST /s/leaves/{id}/cancel", s.studentLeaveCancel)
	mux.HandleFunc("GET /s/leaves/{id}/qr.png", s.studentLeaveQR)
	mux.HandleFunc("GET /s/profile", s.profilePage)
	mux.HandleFunc("POST /s/profile/password", s.profilePassword)
	mux.HandleFunc("POST /s/profile/sessions/revoke", s.profileRevokeOtherSessions)
	mux.HandleFunc("GET /s/notifications", s.notificationsPage)
	mux.HandleFunc("POST /s/notifications/read", s.notificationsRead)
	mux.HandleFunc("GET /s/recover", s.studentRecoverPage)
	mux.HandleFunc("POST /s/recover", s.studentRecoverPost)

	// Teacher / counselor.
	mux.HandleFunc("GET /t", s.teacherDashboard)
	mux.HandleFunc("GET /t/classes", s.teacherClasses)
	mux.HandleFunc("GET /t/classes/new", s.teacherClassNew)
	mux.HandleFunc("POST /t/classes/new", s.teacherClassCreate)
	mux.HandleFunc("GET /t/classes/claim", s.teacherClaimPage)
	mux.HandleFunc("POST /t/classes/claim", s.teacherClaimPost)
	mux.HandleFunc("GET /t/classes/{id}", s.teacherClassDetail)
	mux.HandleFunc("POST /t/classes/{id}/rename", s.teacherClassRename)
	mux.HandleFunc("POST /t/classes/{id}/exit", s.teacherClassExit)
	mux.HandleFunc("GET /t/classes/{id}/students", s.teacherStudents)
	mux.HandleFunc("GET /t/classes/{id}/students/import/template", s.teacherImportTemplate)
	mux.HandleFunc("POST /t/classes/{id}/students/import", s.teacherImportStudents)
	mux.HandleFunc("POST /t/classes/{id}/students/{student_id}/dorm", s.teacherStudentDorm)
	mux.HandleFunc("POST /t/classes/{id}/students/{student_id}/name", s.teacherStudentName)
	mux.HandleFunc("GET /t/classes/{id}/students/{student_id}/leave/new", s.teacherLeaveNewPage)
	mux.HandleFunc("POST /t/classes/{id}/students/{student_id}/leave/new", s.teacherLeaveNewSubmit)
	mux.HandleFunc("GET /t/classes/{id}/imports", s.teacherImports)
	mux.HandleFunc("GET /t/classes/{id}/counselor", s.teacherCounselor)
	mux.HandleFunc("POST /t/classes/{id}/counselor/invite", s.teacherCounselorInvite)
	mux.HandleFunc("POST /t/classes/{id}/counselor/cancel", s.teacherCounselorCancel)
	mux.HandleFunc("GET /t/class-invitations", s.teacherInvitations)
	mux.HandleFunc("POST /t/class-invitations/{id}/respond", s.teacherInvitationRespond)
	mux.HandleFunc("GET /t/export", s.staffExportPage)
	mux.HandleFunc("GET /t/export.xlsx", s.staffExportFile)
	mux.HandleFunc("GET /t/recover", s.staffRecoverPage)
	mux.HandleFunc("POST /t/recover/verify", s.staffRecoverVerify)
	mux.HandleFunc("POST /t/recover/{id}/approve", s.staffRecoverApprove)
	mux.HandleFunc("POST /t/recover/{id}/reject", s.staffRecoverReject)
	mux.HandleFunc("GET /t/leaves/{id}", s.teacherLeaveDetail)
	mux.HandleFunc("POST /t/leaves/{id}/decide", s.teacherLeaveDecide)
	mux.HandleFunc("POST /t/leaves/{id}/time", s.teacherLeaveTime)
	mux.HandleFunc("POST /t/leaves/{id}/proxy", s.teacherLeaveProxy)
	mux.HandleFunc("GET /t/notifications", s.notificationsPage)
	mux.HandleFunc("POST /t/notifications/read", s.notificationsRead)
	mux.HandleFunc("GET /t/profile", s.profilePage)
	mux.HandleFunc("POST /t/profile/password", s.profilePassword)
	mux.HandleFunc("POST /t/profile/sessions/revoke", s.profileRevokeOtherSessions)

	// Community teacher.
	mux.HandleFunc("GET /c", s.communityDashboard)
	mux.HandleFunc("GET /c/buildings", s.communityBuildings)
	mux.HandleFunc("POST /c/buildings", s.communityBuildingsPost)
	mux.HandleFunc("GET /c/students", s.communityStudents)
	mux.HandleFunc("POST /c/students/{student_id}/dorm", s.communityStudentDorm)
	mux.HandleFunc("GET /c/leaves", s.communityLeaves)
	mux.HandleFunc("GET /c/leaves/{id}", s.communityLeaveDetail)
	mux.HandleFunc("GET /c/export", s.communityExportPage)
	mux.HandleFunc("GET /c/export.xlsx", s.communityExportFile)
	mux.HandleFunc("GET /c/recover", s.staffRecoverPage)
	mux.HandleFunc("POST /c/recover/verify", s.staffRecoverVerify)
	mux.HandleFunc("POST /c/recover/{id}/approve", s.staffRecoverApprove)
	mux.HandleFunc("POST /c/recover/{id}/reject", s.staffRecoverReject)
	mux.HandleFunc("GET /c/notifications", s.notificationsPage)
	mux.HandleFunc("POST /c/notifications/read", s.notificationsRead)
	mux.HandleFunc("GET /c/profile", s.profilePage)
	mux.HandleFunc("POST /c/profile/password", s.profilePassword)
	mux.HandleFunc("POST /c/profile/sessions/revoke", s.profileRevokeOtherSessions)

	// Administrator.
	mux.HandleFunc("GET /admin", s.adminDashboard)
	mux.HandleFunc("GET /admin/leaves", s.adminLeaves)
	mux.HandleFunc("GET /admin/leaves/export", func(w http.ResponseWriter, r *http.Request) {
		http.Redirect(w, r, "/admin/export", http.StatusSeeOther)
	})
	mux.HandleFunc("GET /admin/export", s.adminExportPage)
	mux.HandleFunc("GET /admin/export.xlsx", s.adminExportFile)
	mux.HandleFunc("GET /admin/leaves/{id}", s.adminLeaveDetail)
	mux.HandleFunc("POST /admin/leaves/{id}/cancel", s.adminLeaveCancel)
	mux.HandleFunc("POST /admin/leaves/{id}/delete", s.adminLeaveDelete)
	mux.HandleFunc("GET /admin/reports", s.adminReports)
	mux.HandleFunc("GET /admin/classes", s.adminClasses)
	mux.HandleFunc("GET /admin/classes/{id}", s.adminClassDetail)
	mux.HandleFunc("POST /admin/classes/{id}/teacher", s.adminClassTeacher)
	mux.HandleFunc("POST /admin/classes/{id}/counselor", s.adminClassCounselor)
	mux.HandleFunc("POST /admin/classes/{id}/disband", s.adminClassDisband)
	mux.HandleFunc("GET /admin/users", s.adminUsers)
	mux.HandleFunc("POST /admin/users", s.adminUserCreate)
	mux.HandleFunc("GET /admin/users/{id}", s.adminUserDetail)
	mux.HandleFunc("POST /admin/users/{id}/delete", s.adminUserDelete)
	mux.HandleFunc("POST /admin/users/{id}/fix-no", s.adminUserFixNo)
	mux.HandleFunc("POST /admin/users/{id}/class", s.adminUserClass)
	mux.HandleFunc("POST /admin/users/{id}/phone", s.adminUserPhone)
	mux.HandleFunc("POST /admin/users/{id}/reset-link", s.adminUserResetLink)
	mux.HandleFunc("POST /admin/students/{id}/dorm", s.adminStudentDorm)
	mux.HandleFunc("GET /admin/students/{id}/dorm-edits", s.adminStudentDormEdits)
	mux.HandleFunc("GET /admin/imports", s.adminImports)
	mux.HandleFunc("GET /admin/settings/registration-codes", s.adminRegistrationCodes)
	mux.HandleFunc("POST /admin/settings/registration-codes", s.adminRegistrationCodeCreate)
	mux.HandleFunc("POST /admin/settings/registration-codes/{id}", s.adminRegistrationCodeUpdate)
	mux.HandleFunc("POST /admin/settings/registration-codes/{id}/delete", s.adminRegistrationCodeDelete)
	mux.HandleFunc("GET /admin/recover", s.adminRecoverPage)
	mux.HandleFunc("POST /admin/recover/verify", s.adminRecoverVerify)
	mux.HandleFunc("POST /admin/recover/{id}/approve", s.adminRecoverApprove)
	mux.HandleFunc("POST /admin/recover/{id}/reject", s.adminRecoverReject)
	mux.HandleFunc("GET /admin/community", s.adminCommunity)
	mux.HandleFunc("POST /admin/community/{id}", s.adminCommunityPost)
	mux.HandleFunc("GET /admin/security", s.adminSecurity)
	mux.HandleFunc("POST /admin/security/unlock", s.adminSecurityUnlock)
	mux.HandleFunc("GET /admin/audit", s.adminAudit)
	mux.HandleFunc("GET /admin/notifications", s.notificationsPage)
	mux.HandleFunc("POST /admin/notifications/read", s.notificationsRead)
	mux.HandleFunc("GET /admin/profile", s.profilePage)
	mux.HandleFunc("POST /admin/profile/password", s.profilePassword)
	mux.HandleFunc("POST /admin/profile/sessions/revoke", s.profileRevokeOtherSessions)

	// Retained leaves (staff only).
	mux.HandleFunc("GET /archived/leaves", s.archivedLeaves)
	mux.HandleFunc("GET /archived/leaves/{id}", s.archivedLeaveDetail)
	mux.HandleFunc("POST /archived/leaves/{id}/delete", s.archivedLeaveDelete)

	// Fallback.
	mux.HandleFunc("/", s.notFound)
}

func (s *Server) notFound(w http.ResponseWriter, r *http.Request) {
	s.error(w, r, http.StatusNotFound, "页面不存在",
		"找不到该页面；请检查链接是否正确，或返回首页继续操作。")
}
